/**
 * Scope, hoisting, closures — краткий разбор с примерами.
 *
 * Как всё связано:
 *   scope    — где переменная видна;
 *   hoisting — когда она становится доступной в пределах этой области;
 *   closure  — как функция сохраняет доступ к своей области после того,
 *              как внешняя функция уже завершилась.
 *
 * Запуск: node scope-hoisting-closures.js
 */

// ---------------------------------------------------------------------------
// 1. Scope (область видимости)
// ---------------------------------------------------------------------------
// Определяет, где переменная доступна. В JS есть глобальная, функциональная
// и блочная область. `var` видна во всей функции, а `let` и `const` — только
// внутри блока `{}`.

function scopeDemo() {
  if (true) {
    var a = 1;
    let b = 2;
    console.log('внутри блока: b =', b); // 2
  }

  console.log('после блока: a =', a); // 1 — var не ограничена блоком

  try {
    console.log(b); // ReferenceError: b is not defined
  } catch (err) {
    console.log('после блока: b —', err.constructor.name, '—', err.message);
  }
}

// ---------------------------------------------------------------------------
// 2. Hoisting (поднятие)
// ---------------------------------------------------------------------------
// Перед выполнением кода JS «поднимает» объявления наверх их области.
// `var` поднимается и инициализируется как `undefined`.
// `let` и `const` тоже поднимаются, но до строки объявления находятся
// во «временной мёртвой зоне» (TDZ), и обращение к ним даёт ошибку.
// Function declaration поднимается целиком, поэтому её можно вызвать
// до объявления.

function hoistingDemo() {
  console.log('var до объявления: x =', x); // undefined
  var x = 5;
  console.log('var после объявления: x =', x); // 5

  try {
    console.log(y); // ReferenceError (TDZ)
  } catch (err) {
    console.log(
      'let до объявления: y —',
      err.constructor.name,
      '—',
      err.message,
    );
  }
  let y = 5;
  console.log('let после объявления: y =', y); // 5

  sayHi(); // работает: function declaration поднята целиком

  function sayHi() {
    console.log('sayHi(): hi');
  }
}

// ---------------------------------------------------------------------------
// 3. Closures (замыкания)
// ---------------------------------------------------------------------------
// Функция запоминает переменные из области, где она была создана, даже после
// того как внешняя функция завершилась. Используется для приватного состояния,
// фабрик функций, колбэков.

function counter() {
  let count = 0;
  return () => ++count;
}

function closureDemo() {
  const inc = counter();
  console.log('inc() =', inc()); // 1
  console.log('inc() =', inc()); // 2

  // `count` недоступна снаружи, но внутренняя функция продолжает её видеть
  // и менять. Каждый вызов counter() создаёт новое независимое состояние.
  const inc2 = counter();
  console.log('новый счётчик, inc2() =', inc2()); // 1 — своё замыкание

  console.log('typeof count снаружи =', typeof count); // undefined
}

// ---------------------------------------------------------------------------

function main() {
  console.log('=== 1. Scope ===');
  scopeDemo();

  console.log('\n=== 2. Hoisting ===');
  hoistingDemo();

  console.log('\n=== 3. Closures ===');
  closureDemo();
}

main();
