// ---------------------------------------------------------------------------
// 1. Destructuring (деструктуризация)
// ---------------------------------------------------------------------------
// Позволяет «распаковать» значения из массива или свойства из объекта
// в отдельные переменные.

function destructuringDemo() {
  const user = {
    name: 'Анна',
    age: 28,
  };
  const { name, age } = user;
  console.log(name, age); // Анна 28
}

// ---------------------------------------------------------------------------
// 2. Spread / Rest
// ---------------------------------------------------------------------------
// Синтаксис один (`...`), но роль разная:
//   spread — «разворачивает» массив или объект в отдельные элементы;
//   rest   — наоборот, «собирает» оставшиеся элементы в массив или объект.

function sum(first, ...others) {
  return first + others.reduce((s, n) => s + n, 0);
}

function spreadRestDemo() {
  // Spread: копируем и дополняем
  const a = [1, 2];
  const b = [...a, 3];
  console.log('spread:', b); // [1, 2, 3]

  // Rest: собираем остаток аргументов
  console.log('rest в функции:', sum(1, 2, 3)); // 6
}

// --- Rest на пальцах ---------------------------------------------------------
// Rest означает «всё остальное сложи в одну кучу».
// Представь, что раздаёшь конфеты: первую берёшь себе, а все остальные кладёшь
// в пакет. Вот этот пакет и есть rest.

function restExplained() {
  const [first, ...rest] = [10, 20, 30, 40];

  console.log('first =', first); // 10
  console.log('rest  =', rest); // [20, 30, 40]
  // first забрал первое число, а ...rest собрал всё, что осталось,
  // в новый массив.

  // С функцией то же самое: сколько бы аргументов ни передал,
  // ...numbers соберёт их все в один массив.
  function show(...numbers) {
    console.log('show():', numbers);
  }

  show(1, 2, 3); // [1, 2, 3]
}

// --- Spread на пальцах -------------------------------------------------------
// Представь коробку с тремя яблоками. Коробка — это массив [🍎, 🍎, 🍎].
// «Разобрать» значит достать яблоки из коробки и выложить их по одному.
// Без точек ты передаёшь коробку. С точками передаёшь то, что внутри,
// по отдельности.

function spreadExplained() {
  const box = [1, 2, 3];

  console.log(box); // [1, 2, 3]  ← коробка целиком
  console.log(...box); // 1 2 3      ← яблоки вынули из коробки

  // Зачем это нужно: чтобы переложить яблоки из одной коробки в другую.
  const wrong = [box, 4]; // [[1, 2, 3], 4]  ← коробка внутри коробки
  const right = [...box, 4]; // [1, 2, 3, 4]    ← яблоки высыпали в новую коробку

  console.log('wrong:', wrong);
  console.log('right:', right);

  // Итого:
  //   Spread (...box)  вынимает яблоки из коробки.
  //   Rest   (...rest) складывает яблоки в коробку.
  // Точки одинаковые, действие противоположное.
}

// ---------------------------------------------------------------------------
// 3. Template literals (шаблонные строки)
// ---------------------------------------------------------------------------
// Пишутся в обратных кавычках. Позволяют вставлять выражения через `${}`
// и писать многострочный текст без `\n`.

function templateLiteralsDemo() {
  const item = 'кофе';
  const price = 3;
  console.log(`Цена за ${item}: ${price * 2} лари`);
  // Цена за кофе: 6 лари
}

// ---------------------------------------------------------------------------

function main() {
  console.log('=== 1. Destructuring ===');
  destructuringDemo();

  console.log('\n=== 2. Spread / Rest ===');
  spreadRestDemo();

  console.log('\n--- Rest на пальцах ---');
  restExplained();

  console.log('\n--- Spread на пальцах ---');
  spreadExplained();

  console.log('\n=== 3. Template literals ===');
  templateLiteralsDemo();
}

main();
