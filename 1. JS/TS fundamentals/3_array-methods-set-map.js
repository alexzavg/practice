// ---------------------------------------------------------------------------
// 1. Методы массивов
// ---------------------------------------------------------------------------
// Общее: map/filter/reduce не мутируют исходный массив, методы можно чейнить.

function arrayMethodsDemo() {
  // map: преобразует каждый элемент, возвращает новый массив той же длины.
  console.log(
    'map:',
    [1, 2, 3].map((x) => x * 2),
  ); // [2, 4, 6]

  // filter: оставляет элементы, для которых колбэк вернул true.
  console.log(
    'filter:',
    [1, 2, 3, 4].filter((x) => x % 2 === 0),
  ); // [2, 4]

  // reduce: сворачивает массив в одно значение (сумма, объект, что угодно).
  // Всегда передавай начальное значение.
  console.log(
    'reduce:',
    [1, 2, 3].reduce((acc, x) => acc + x, 0),
  ); // 6

  // find: возвращает первый подходящий элемент или undefined.
  // Есть findIndex для индекса.
  console.log(
    'find:',
    [
      {
        id: 1,
      },
      {
        id: 2,
      },
    ].find((u) => u.id === 2),
  ); // {id: 2}

  // some: true, если хотя бы один элемент подходит.
  // Останавливается на первом совпадении.
  console.log(
    'some:',
    [1, 5, 10].some((x) => x > 8),
  ); // true

  // every: true, если все элементы подходят. На пустом массиве всегда true.
  console.log(
    'every:',
    [2, 4, 6].every((x) => x % 2 === 0),
  ); // true
}

// ---------------------------------------------------------------------------
// 2. Set
// ---------------------------------------------------------------------------
// Коллекция уникальных значений, сравнение по SameValueZero
// (объекты сравниваются по ссылке).
// Методы: add, has, delete, size. Итерируется в порядке добавления.
// has работает за O(1), в отличие от array.includes за O(n).

function setDemo() {
  const unique = [...new Set([1, 2, 2, 3])];
  console.log('unique:', unique); // [1, 2, 3]
}

// ---------------------------------------------------------------------------
// 3. Map
// ---------------------------------------------------------------------------
// Пары ключ-значение, ключом может быть что угодно (объект, функция, NaN).
// Методы: set, get, has, delete, size. Сохраняет порядок вставки.
// Лучше обычного объекта для частых добавлений/удалений и нестроковых ключей.

function mapDemo() {
  const counts = new Map();
  for (const w of ['a', 'b', 'a']) counts.set(w, (counts.get(w) ?? 0) + 1);
  console.log('counts:', counts); // Map { 'a' => 2, 'b' => 1 }
}

// ---------------------------------------------------------------------------

function main() {
  console.log('=== 1. Методы массивов ===');
  arrayMethodsDemo();

  console.log('\n=== 2. Set ===');
  setDemo();

  console.log('\n=== 3. Map ===');
  mapDemo();
}

main();
