/**
 * skip() — временное отключение тестов (Jest).
 *
 * - test.skip / it.skip / describe.skip не запускают тест, но показывают его
 *   в отчёте со статусом skipped. Это честнее, чем закомментировать код:
 *   отключённый тест остаётся видимым.
 * - xit и xdescribe — короткие синонимы skip.
 * - Тело пропущенного теста не выполняется совсем, поэтому ошибка внутри
 *   не уронит прогон.
 * - Для условного пропуска есть test.skip.each и проверки внутри теста.
 * - Правило: у skip должна быть причина в комментарии и задача на возврат,
 *   иначе тест останется выключенным навсегда.
 *
 * Запуск: npx jest "2. Core testing fundamentals/jest/5_skip.test.js"
 */

const parser = {
  parse: (text) => text.trim(),
};

describe('Парсер', () => {
  it('убирает пробелы по краям', () => {
    expect(parser.parse('  привет  ')).toBe('привет');
  });

  // Пропущен: ждём реализацию multiline-режима, задача PRACTICE-42.
  it.skip('разбирает многострочный текст', () => {
    expect(parser.parse('a\nb')).toBe('a b'); // упало бы, но не запускается
  });

  xit('xit — короткий синоним it.skip', () => {
    throw new Error('это тело не выполнится');
  });
});

describe.skip('Целый блок отключён', () => {
  it('этот тест тоже пропущен', () => {
    expect(true).toBe(false);
  });
});
