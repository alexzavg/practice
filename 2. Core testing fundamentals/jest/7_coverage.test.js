/**
 * Покрытие кода (coverage) — запуск через CLI.
 *
 * - Покрытие показывает, какие строки и ветки исходного кода выполнились
 *   во время тестов. Это метрика полноты прогона, а не качества тестов.
 * - Четыре показателя: % Stmts (инструкции), % Branch (ветки if/switch/?:),
 *   % Funcs (функции), % Lines (строки).
 * - Колонка "Uncovered Line #s" — самое полезное: конкретные номера строк,
 *   куда тесты не дошли.
 * - Считается по исходным файлам, а не по тестам, поэтому проверяемый код
 *   держат в отдельном модуле (здесь src/calculator.js).
 * - Флаг: npx jest --coverage. Порог можно задать через coverageThreshold
 *   в конфиге, тогда низкое покрытие роняет прогон.
 *
 * Запуск с отчётом:
 *   npm run test:jest:coverage
 */

const { sum, divide, discount } = require('../src/calculator');

describe('calculator', () => {
  it('складывает числа', () => {
    expect(sum(2, 3)).toBe(5);
  });

  it('делит числа', () => {
    expect(divide(10, 2)).toBe(5);
  });

  it('бросает ошибку при делении на ноль', () => {
    expect(() => divide(1, 0)).toThrow('Деление на ноль');
  });

  it('считает скидку для gold', () => {
    expect(discount(100, 'gold')).toBe(80);
  });

  // Ветки 'silver' и "без уровня" намеренно не покрыты:
  // в отчёте они появятся в колонке Uncovered Line #s.
});
