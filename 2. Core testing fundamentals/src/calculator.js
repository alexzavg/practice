/**
 * Модуль-подопытный для замеров покрытия.
 *
 * Лежит отдельно от тестов намеренно: покрытие считается по исходному коду,
 * а не по самим тестам. Если функция объявлена внутри тестового файла,
 * в отчёте о покрытии она не появится.
 *
 * Часть веток здесь специально не покрыта тестами, чтобы в отчёте были видны
 * непокрытые строки.
 */

function sum(a, b) {
  return a + b;
}

function divide(a, b) {
  if (b === 0) {
    throw new Error('Деление на ноль'); // эта ветка покрыта тестом
  }
  return a / b;
}

function discount(total, level) {
  if (level === 'gold') {
    return total * 0.8; // покрыто
  }
  if (level === 'silver') {
    return total * 0.9; // не покрыто — видно в отчёте
  }
  return total; // не покрыто
}

module.exports = {
  sum,
  divide,
  discount,
};
