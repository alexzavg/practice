/**
 * Покрытие кода в Jasmine — через c8.
 *
 * - Своего покрытия у Jasmine тоже нет, подход такой же, как у Mocha:
 *   c8 jasmine.
 * - Общее правило: покрытие даёт только Jest из коробки. Mocha и Jasmine
 *   комбинируют со сторонним инструментом.
 * - Высокий процент покрытия не означает, что тесты хорошие: строка может
 *   выполниться без единой проверки результата.
 * - Полезнее смотреть на непокрытые ветки, чем на общий процент.
 *
 * Запуск: npm run test:jasmine:coverage
 */

const { sum, divide, discount } = require('../src/calculator');

describe('calculator (Jasmine)', () => {
  it('складывает числа', () => {
    expect(sum(2, 3)).toBe(5);
  });

  it('бросает ошибку при делении на ноль', () => {
    expect(() => divide(1, 0)).toThrowError('Деление на ноль');
  });

  it('считает скидку для gold', () => {
    expect(discount(100, 'gold')).toBe(80);
  });
});
