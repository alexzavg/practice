/**
 * Пропуск и фокус в Jasmine: xit / xdescribe, fit / fdescribe, pending().
 *
 * - xit и xdescribe пропускают тест или блок. Отдельного .skip в Jasmine нет,
 *   но it.skip работает как алиас в новых версиях.
 * - pending('причина') помечает тест незавершённым прямо во время выполнения,
 *   причина попадает в отчёт.
 * - it без функции — тоже pending, как заготовка.
 * - fit и fdescribe ("focused") запускают только помеченное. Важное отличие
 *   от Jest: фокус действует на весь прогон, а не на один файл, поэтому
 *   забытый fit выключает вообще все спеки проекта.
 * - Для одиночного запуска лучше ключ --filter="часть имени", он не требует
 *   править код.
 *
 * Запуск: npx jasmine --config="2. Core testing fundamentals/jasmine/jasmine.json" --filter="Парсер"
 */

const parser = {
  parse: (text) => text.trim(),
};

describe('Парсер', () => {
  it('убирает пробелы по краям', () => {
    expect(parser.parse('  привет  ')).toBe('привет');
  });

  // Пропущен: ждём multiline-режим, задача PRACTICE-42.
  xit('разбирает многострочный текст', () => {
    expect(parser.parse('a\nb')).toBe('a b');
  });

  it('заготовка на будущее'); // без колбэка — pending

  it('пропуск по условию во время выполнения', () => {
    if (process.platform !== 'win32') {
      pending('тест только для Windows');
    }
    expect(true).toBe(true);
  });
});

xdescribe('Целый блок отключён', () => {
  it('этот тест не выполнится', () => {
    expect(true).toBe(false);
  });
});

